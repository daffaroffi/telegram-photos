fn distance_km(lat1: f64, lon1: f64, lat2: f64, lon2: f64) -> f64 {
    const R: f64 = 6371.0;
    let d_lat = (lat2 - lat1).to_radians();
    let d_lon = (lon2 - lon1).to_radians();
    let a = (d_lat / 2.0).sin().powi(2)
        + lat1.to_radians().cos() * lat2.to_radians().cos() * (d_lon / 2.0).sin().powi(2);
    2.0 * R * a.sqrt().atan2((1.0 - a).sqrt())
}

/// Offline reverse geocode. Returns `(city, country)` or `(None, None)`.
pub fn reverse_geocode(lat: f64, lon: f64) -> (Option<String>, Option<String>) {
    if !lat.is_finite() || !lon.is_finite() {
        return (None, None);
    }
    let mut best: Option<(&str, &str, f64)> = None;
    for (city, country, c_lat, c_lon) in KNOWN_PLACES {
        let d = distance_km(lat, lon, *c_lat, *c_lon);
        if d <= 50.0 {
            match best {
                Some((_, _, best_d)) if best_d <= d => {}
                _ => best = Some((city, country, d)),
            }
        }
    }
    match best {
        Some((city, country, _)) => (Some(city.to_string()), Some(country.to_string())),
        None => (None, None),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn geocodes_known_cities() {
        let (city, country) = reverse_geocode(-6.2088, 106.8456);
        assert_eq!(city.as_deref(), Some("Jakarta"));
        assert_eq!(country.as_deref(), Some("Indonesia"));

        let (city2, _) = reverse_geocode(-7.9839, 112.6214);
        assert_eq!(city2.as_deref(), Some("Malang"));
    }

    #[test]
    fn returns_none_for_unknown_area() {
        let (city, country) = reverse_geocode(0.0, 0.0);
        assert!(city.is_none() && country.is_none());
    }
}
